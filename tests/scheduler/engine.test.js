import test from 'node:test';
import assert from 'node:assert/strict';
import {parseText,check,alternatives,initialRules,addDays,todayKST,stamp} from '../../utils/scheduler/engine.js';
const now=Date.parse('2026-09-16T10:00:00+09:00');
const e={title:'운동',date:'2026-09-17',time:'20:00',duration:60,category:'exercise'};
const rules=structuredClone(initialRules);
const existing=[{...e,id:'a',title:'저녁 약속',time:'19:30',duration:90,category:'personal'}];
test('01 KST 날짜 경계',()=>assert.equal(todayKST(new Date('2026-09-16T16:00:00Z')),'2026-09-17'));
test('02 연도 이동',()=>assert.equal(addDays('2026-12-31',1),'2027-01-01'));
test('03 오후 파싱',()=>assert.equal(parseText('내일 오후 8시 운동',new Date(now)).time,'20:00'));
test('04 모호한 시간 질문',()=>assert.equal(parseText('내일 8시 운동일정',new Date(now)).ambiguous,true));
test('05 정오',()=>assert.equal(parseText('내일 오후 12시 식사',new Date(now)).time,'12:00'));
test('06 자정',()=>assert.equal(parseText('내일 오전 12시 독서',new Date(now)).time,'00:00'));
test('07 카테고리',()=>assert.equal(parseText('모레 오전 10시 팀 회의',new Date(now)).category,'work'));
test('08 시간과 소요시간',()=>assert.equal(parseText('내일 오후 3시 공부 2시간',new Date(now)).duration,120));
test('09 반 시간',()=>assert.equal(parseText('내일 오후 3시 반 공부',new Date(now)).time,'15:30'));
test('10 빈 입력',()=>assert.throws(()=>parseText('',new Date(now))));
test('11 불가능한 날짜',()=>assert.throws(()=>parseText('2026-02-30 오후 3시 공부',new Date(now))));
test('12 시간 오류',()=>assert.throws(()=>parseText('내일 25시 운동',new Date(now))));
test('13 정상 등록',()=>assert.equal(check(e,[],rules,now).ok,true));
test('14 겹침 감지',()=>assert.equal(check(e,existing,rules,now).reasons[0].type,'overlap'));
test('15 여유시간 부족',()=>assert.equal(check({...e,time:'21:00'},existing,rules,now).reasons.some(x=>x.type==='gap'),true));
test('16 정확한 여유시간 허용',()=>assert.equal(check({...e,time:'21:15',duration:45},existing,rules,now).ok,true));
test('17 운동 종료시간',()=>assert.equal(check({...e,time:'21:15'},[],rules,now).reasons[0].type,'category'));
test('18 주말 업무 차단/해제',()=>{const w={...e,date:'2026-09-19',category:'work'};assert.equal(check(w,[],rules,now).ok,false);assert.equal(check(w,[],{...rules,weekendWork:false},now).ok,true)});
test('19 과거 및 잘못된 값 차단',()=>{assert.equal(check({...e,date:'2026-09-15'},[],rules,now).ok,false);assert.equal(check({...e,date:''},[],rules,now).ok,false);assert.deepEqual(alternatives({...e,date:''},[],rules,now),[])});
test('20 대안 전부 재검사 통과',()=>{const a=alternatives(e,existing,rules,now);assert.equal(a.length,3);a.forEach(x=>{assert.ok(check(x,existing,rules,now).ok);assert.notEqual(stamp(x.date,x.time),stamp(e.date,e.time))})});
